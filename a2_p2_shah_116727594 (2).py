import torch.nn.functional as F

def get_probs(model, tokenizer, text, device):
    model.eval()
    tokens = tokenizer.encode(text, return_tensors="pt").to(device)

    with torch.no_grad():
        logits, _ = model(tokens)  # Get logits from model

    probs = F.softmax(logits, dim=-1)  # Apply softmax to get probabilities
    return probs

import math

def get_perplexity(probs):
    """
    Compute the perplexity given a list of token probabilities.

    :param probs: List of probabilities for each token in a sequence.
    :return: Perplexity score (float)
    """
    if not probs or any(p == 0 for p in probs):
        return float('inf')  # Avoid log(0) errors

    log_sum = sum(math.log(p) for p in probs)  # Sum of log probabilities
    N = len(probs)  # Number of tokens

    perplexity = math.exp(-log_sum / N)  # Compute perplexity
    return perplexity

