# Checkpoint 2.4: Autoregressive Lyric Generation
def generate(model, tokenizer, start_phrase, max_len, device):
    model.eval()
    tokens = tokenizer.encode(start_phrase)
    generated_tokens = tokens.copy()
    hidden_state = None

    with torch.no_grad():
        if len(tokens) > 1:
            X = torch.tensor([tokens[:-1]], device=device)
            logits, hidden_state = model(X)
            next_token = torch.argmax(logits[:, -1, :], dim=-1).item()
            generated_tokens.append(next_token)
        else:
            next_token = tokens[0]

        for _ in range(max_len - len(generated_tokens)):
            X = torch.tensor([[next_token]], device=device)
            logits, hidden_state = model.stepwise_forward(X, hidden_state)
            next_token = torch.argmax(logits, dim=-1).item()
            generated_tokens.append(next_token)
            if next_token in [tokenizer.eos_token_id, tokenizer.pad_token_id]:
                break

    return generated_tokens

