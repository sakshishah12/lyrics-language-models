class RecurrentLM(nn.Module):
    def __init__(self, vocab_size, embed_dim, rnn_hidden_dim):
        super().__init__()
        self.embedding = nn.Embedding(vocab_size, embed_dim)
        self.gru = nn.GRU(embed_dim, rnn_hidden_dim, batch_first=True)
        self.layer_norm = nn.LayerNorm(rnn_hidden_dim)
        self.projection = nn.Linear(rnn_hidden_dim, vocab_size)

    def forward(self, x):
        embedded = self.embedding(x)  # (batch_size, seq_len, embed_dim)
        gru_out, hidden_state = self.gru(embedded)  # (batch_size, seq_len, rnn_hidden_dim), (1, batch_size, rnn_hidden_dim)
        normed = self.layer_norm(gru_out)
        logits = self.projection(normed)  # (batch_size, seq_len, vocab_size)
        return logits, hidden_state

    def stepwise_forward(self, x, prev_hidden_state):
        embedded = self.embedding(x)  # (1, 1, embed_dim)
        gru_out, hidden_state = self.gru(embedded, prev_hidden_state)  # (1, 1, rnn_hidden_dim)
        normed = self.layer_norm(gru_out)
        logits = self.projection(normed)  # (1, 1, vocab_size)
        return logits, hidden_state

